#!/usr/bin/env python3
"""Generate the small GB2312 bitmap font used by the watch chat UI.

The watch only ships a 5x7 ASCII font.  Chat replies are Chinese, so the AI
page needs a compact CJK font in flash.  This generator renders GB2312's
7445 characters at 14x14 from a system CJK font and writes a sorted codepoint
table plus packed 1-bpp glyph rows.

Usage:
    python3 tools/gen_cjk_font.py

The output files are checked in so a normal firmware build does not need PIL
or a system font.  Source Han Sans / Noto Sans CJK are OFL licensed; only the
rasterized bitmap is embedded here.
"""

from __future__ import annotations

import pathlib

from PIL import Image, ImageDraw, ImageFont

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT_C = ROOT / "components/watchshell/src/watch_font_cjk.c"
OUT_H = ROOT / "components/watchshell/include/watch_font_cjk.h"
FONT_CANDIDATES = [
    "/usr/share/fonts/noto-cjk/NotoSansCJK-Regular.ttc",
    "/usr/share/fonts/adobe-source-han-sans/SourceHanSansCN-Regular.otf",
    "/usr/share/fonts/adobe-source-han-sans/SourceHanSansCN-Light.otf",
]

SIZE = 14
ROW_BYTES = 2
GLYPH_BYTES = SIZE * ROW_BYTES


def collect_chars() -> list[str]:
    chars = set()
    for first in range(0xA1, 0xF8):
        for second in range(0xA1, 0xFF):
            try:
                chars.add(bytes((first, second)).decode("gb2312"))
            except UnicodeDecodeError:
                pass
    # GB2312 decoding can yield multi-codepoint sequences; the bitmap renderer
    # handles one Unicode codepoint per glyph, so keep only single codepoints.
    return sorted(ch for ch in chars if len(ch) == 1 and ord(ch) > 0x7F)


def load_font() -> ImageFont.FreeTypeFont:
    for path in FONT_CANDIDATES:
        if pathlib.Path(path).exists():
            try:
                return ImageFont.truetype(path, SIZE, index=2)
            except OSError:
                return ImageFont.truetype(path, SIZE)
    raise SystemExit("No CJK font found; install Noto Sans CJK or Source Han Sans")


def render(font: ImageFont.FreeTypeFont, ch: str) -> bytes:
    image = Image.new("1", (SIZE, SIZE), 0)
    draw = ImageDraw.Draw(image)
    # Baseline anchor keeps full-width punctuation (，。！) at the bottom of
    # the cell while CJK ideographs remain vertically centred by the font.
    draw.text((0, 12), ch, font=font, fill=1, anchor="ls")
    packed = bytearray()
    for y in range(SIZE):
        bits = 0
        for x in range(SIZE):
            if image.getpixel((x, y)):
                bits |= 1 << (15 - x)
        packed.extend((bits >> 8, bits & 0xFF))
    return bytes(packed)


def main() -> None:
    chars = collect_chars()
    font = load_font()
    codepoints = [ord(ch) for ch in chars]
    glyphs = [render(font, ch) for ch in chars]

    header = f"""/* Generated by tools/gen_cjk_font.py. Do not edit. */
#pragma once

#include <stdint.h>

#define WATCH_FONT_CJK_SIZE {SIZE}
#define WATCH_FONT_CJK_ROW_BYTES {ROW_BYTES}
#define WATCH_FONT_CJK_GLYPH_BYTES {GLYPH_BYTES}
#define WATCH_FONT_CJK_COUNT {len(chars)}u

/* Sorted Unicode codepoints; bitmap[index] is a 14x14 1-bpp glyph. */
extern const uint32_t watch_font_cjk_codepoints[WATCH_FONT_CJK_COUNT];
extern const uint8_t watch_font_cjk_bitmap[WATCH_FONT_CJK_COUNT * WATCH_FONT_CJK_GLYPH_BYTES];
"""
    OUT_H.write_text(header, encoding="utf-8")

    with OUT_C.open("w", encoding="utf-8") as out:
        out.write("/* Generated by tools/gen_cjk_font.py. Do not edit. */\n")
        out.write('#include "watch_font_cjk.h"\n\n')
        out.write("const uint32_t watch_font_cjk_codepoints[WATCH_FONT_CJK_COUNT] = {\n")
        for i in range(0, len(codepoints), 8):
            group = ", ".join("0x%04X" % cp for cp in codepoints[i:i + 8])
            out.write("    " + group + ",\n")
        out.write("};\n\n")
        out.write("const uint8_t watch_font_cjk_bitmap[WATCH_FONT_CJK_COUNT * WATCH_FONT_CJK_GLYPH_BYTES] = {\n")
        for glyph in glyphs:
            out.write("    " + ",".join("0x%02X" % value for value in glyph) + ",\n")
        out.write("};\n")

    print(f"wrote {len(chars)} glyphs, {len(chars) * GLYPH_BYTES} bytes bitmap")


if __name__ == "__main__":
    main()
